/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  HAL_Init();

  SystemClock_Config();

  MX_GPIO_Init();
  MX_CAN1_Init();
  MX_USART2_UART_Init();

  /* USER CODE BEGIN 2 */
  /* CAN filter: accept only standard ID 0x321 */
  CAN_Filter.FilterBank = 0;
  CAN_Filter.FilterMode = CAN_FILTERMODE_IDMASK;
  CAN_Filter.FilterScale = CAN_FILTERSCALE_32BIT;

  CAN_Filter.FilterIdHigh = (0x321 << 5);
  CAN_Filter.FilterIdLow = 0x0000;
  CAN_Filter.FilterMaskIdHigh = (0x7FF << 5);
  CAN_Filter.FilterMaskIdLow = 0x0000;

  CAN_Filter.FilterFIFOAssignment = CAN_FILTER_FIFO0;
  CAN_Filter.FilterActivation = ENABLE;
  CAN_Filter.SlaveStartFilterBank = 14;

  if (HAL_CAN_ConfigFilter(&hcan1, &CAN_Filter) != HAL_OK)
  {
    Error_Handler();
  }

  if (HAL_CAN_Start(&hcan1) != HAL_OK)
  {
    Error_Handler();
  }

  char startup_str[] = "CAN Receiver Ready\r\n";
  HAL_UART_Transmit(&huart2,
                    (uint8_t *)startup_str,
                    sizeof(startup_str) - 1U,
                    HAL_MAX_DELAY);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    if (HAL_CAN_GetRxFifoFillLevel(&hcan1, CAN_RX_FIFO0) > 0U)
    {
      if (HAL_CAN_GetRxMessage(&hcan1, CAN_RX_FIFO0, &RxHeader, RxData) == HAL_OK)
      {
        if ((RxHeader.IDE == CAN_ID_STD) &&
            (RxHeader.StdId == 0x321) &&
            (RxHeader.DLC >= 2U))
        {
          batt = ((uint16_t)RxData[0] << 8) | RxData[1];
          battery_voltage = batt / 100.0f;

          snprintf(str, sizeof(str), "Battery_Voltage = %.2f V\r\n", battery_voltage);
          HAL_UART_Transmit(&huart2,
                            (uint8_t *)str,
                            strlen(str),
                            HAL_MAX_DELAY);

          HAL_GPIO_TogglePin(GPIOD, GPIO_PIN_12);
        }
      }
    }

    HAL_Delay(50);
  }
  /* USER CODE END WHILE */
}

